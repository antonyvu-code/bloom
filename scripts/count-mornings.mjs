// Prebuild: derive the real number of research mornings from the daily digest.
// BLOOM's core claim is "every flower is one morning of research" — so the seed
// count must come from the actual log, not a hand-typed number. This scans the
// sibling webdesign-digest folder for YYYY-MM-DD.md entries and writes a small
// generated module the app imports. Runs on `predev` and `prebuild`.

import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const digestDir = join(here, '..', '..', 'webdesign-digest');
const outFile = join(here, '..', 'src', 'mornings.generated.js');

const DATE_FILE = /^(\d{4}-\d{2}-\d{2})\.md$/;

let dates = [];
try {
  if (existsSync(digestDir)) {
    dates = readdirSync(digestDir)
      .map((f) => (f.match(DATE_FILE) || [])[1])
      .filter(Boolean)
      .sort();
  }
} catch {
  // Folder unreadable — fall through to a safe, honest fallback.
}

// Fallback keeps the site truthful even if the digest is absent at build time:
// one morning, dated today. Never invents a bigger number than we can prove.
if (dates.length === 0) {
  dates = [new Date().toISOString().slice(0, 10)];
}

const mornings = dates.length;
const latest = dates[dates.length - 1];
const first = dates[0];

const banner = '// AUTO-GENERATED by scripts/count-mornings.mjs — do not edit by hand.\n';
const body =
  `export const MORNINGS = ${mornings};\n` +
  `export const FIRST_MORNING = ${JSON.stringify(first)};\n` +
  `export const LATEST_MORNING = ${JSON.stringify(latest)};\n`;

writeFileSync(outFile, banner + body);
console.log(`[bloom] ${mornings} morning(s) counted from digest (${first} → ${latest}).`);
